# 2. Per-class precision / recall / F1 bar chart
#

def plot_class_metrics(y_test, y_pred, class_names=('Normal', 'Abnormal')):
    report = classification_report(y_test, y_pred, target_names=class_names,
                                     output_dict=True)

    metrics = ['precision', 'recall', 'f1-score']
    colors = ['#877499', '#679F9F', '#E6D4BF']
    x = np.arange(len(class_names))
    width = 0.25

    fig, ax = plt.subplots(figsize=(6, 4))
    for i, m in enumerate(metrics):
        vals = [report[c][m] for c in class_names]
        ax.bar(x + i * width, vals, width, label=m, color=colors[i])

    ax.set_xticks(x + width)
    ax.set_xticklabels(class_names)
    ax.set_ylim(0, 1.05)
    ax.set_ylabel('Score')
    ax.set_title('Per-class metrics')
    ax.legend()
    plt.tight_layout()
    plt.savefig('class_metrics.png', dpi=150)
    plt.show()



# 3. K-selection curve (accuracy/F1 vs k)



def plot_k_curve(X_train, y_train, X_test, y_test, k_values=range(1, 21)):
    from sklearn.neighbors import KNeighborsClassifier
    from sklearn.metrics import f1_score, accuracy_score

    f1s, accs = [], []
    for k in k_values:
        clf = KNeighborsClassifier(n_neighbors=k)
        clf.fit(X_train, y_train)
        y_pred = clf.predict(X_test)
        f1s.append(f1_score(y_test, y_pred, average='macro'))
        accs.append(accuracy_score(y_test, y_pred))

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(list(k_values), accs, marker='o', label='Accuracy')
    ax.plot(list(k_values), f1s, marker='s', label='Macro F1')
    ax.set_xlabel('k (number of neighbors)')
    ax.set_ylabel('Score')
    ax.set_title('KNN performance vs k')
    ax.legend()
    ax.grid(alpha=0.3)
    plt.tight_layout()
    plt.savefig('k_selection_curve.png', dpi=150)
    plt.show()



# 4. Average beat waveform: Normal vs Abnormal
#     shows visually what the model is trying to tell apart.


def plot_average_waveforms(data, labels):
    labels = np.ravel(labels)
    normal_mean = data[labels == 0].mean(axis=0)
    normal_std = data[labels == 0].std(axis=0)
    abnormal_mean = data[labels == 1].mean(axis=0)
    abnormal_std = data[labels == 1].std(axis=0)

    t = np.arange(data.shape[1])

    fig, ax = plt.subplots(figsize=(7, 4))
    ax.plot(t, normal_mean, label='Normal (mean)', color='steelblue')
    ax.fill_between(t, normal_mean - normal_std, normal_mean + normal_std,
                     alpha=0.2, color='steelblue')
    ax.plot(t, abnormal_mean, label='Abnormal (mean)', color='indianred')
    ax.fill_between(t, abnormal_mean - abnormal_std, abnormal_mean + abnormal_std,
                     alpha=0.2, color='indianred')

    ax.set_xlabel('Time (samples)')
    ax.set_ylabel('Amplitude')
    ax.set_title('Average heartbeat shape: Normal vs Abnormal (\u00b1 1 SD)')
    ax.legend()
    plt.tight_layout()
    plt.savefig('average_waveforms.png', dpi=150)
    plt.show()



# 5. Error analysis:
#    Compares the average shape of Abnormal beats the model got right (true
#    positives) against ones it missed (false negatives) and separately,
#    Normal beats it wrongly flagged as Abnormal (false positives).
#    X_test rows are the actual waveforms.


def plot_error_analysis(X_test, y_test, y_pred):
    y_test = np.ravel(y_test)
    y_pred = np.ravel(y_pred)

    tp_mask = (y_test == 1) & (y_pred == 1)   # correctly caught Abnormal
    fn_mask = (y_test == 1) & (y_pred == 0)   # missed Abnormal (false negative)
    fp_mask = (y_test == 0) & (y_pred == 1)   # Normal wrongly flagged (false positive)

    n_tp, n_fn, n_fp = tp_mask.sum(), fn_mask.sum(), fp_mask.sum()
    print(f'True Positives (caught Abnormal): {n_tp}')
    print(f'False Negatives (missed Abnormal): {n_fn}')
    print(f'False Positives (Normal flagged as Abnormal): {n_fp}')

    t = np.arange(X_test.shape[1])
    fig, axes = plt.subplots(1, 2, figsize=(12, 4))

    # Panel 1: caught vs missed Abnormal beats
    ax = axes[0]
    if n_tp > 0:
        mean_tp = X_test[tp_mask].mean(axis=0)
        ax.plot(t, mean_tp, label=f'Caught (TP, n={n_tp})', color='seagreen')
    if n_fn > 0:
        mean_fn = X_test[fn_mask].mean(axis=0)
        ax.plot(t, mean_fn, label=f'Missed (FN, n={n_fn})', color='indianred')
    ax.set_title('Abnormal beats: caught vs missed')
    ax.set_xlabel('Time (samples)')
    ax.set_ylabel('Amplitude')
    ax.legend()

    # Panel 2: a handful of individual false-negative waveforms
    ax = axes[1]
    fn_indices = np.where(fn_mask)[0]
    n_show = min(5, len(fn_indices))
    for idx in fn_indices[:n_show]:
        ax.plot(t, X_test[idx], alpha=0.6)
    ax.set_title(f'{n_show} individual missed Abnormal beats')
    ax.set_xlabel('Time (samples)')
    ax.set_ylabel('Amplitude')

    plt.tight_layout()
    plt.savefig('error_analysis.png', dpi=150)
    plt.show()

    return {'true_positives': n_tp, 'false_negatives': n_fn, 'false_positives': n_fp}


