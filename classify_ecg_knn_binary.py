    import json
    from datetime import datetime

    def log_results(y_test, y_pred, k, filename='results_log.json'):
        entry = {
            'timestamp': datetime.now().isoformat(),
            'best_k': k,
            'classification_report': classification_report(
                y_test, y_pred, target_names=['Normal', 'Abnormal'], output_dict=True
            ),
            'confusion_matrix': confusion_matrix(y_test, y_pred).tolist(),
        }
        try:
            with open(filename) as f:
                log = json.load(f)
        except FileNotFoundError:
            log = []
        log.append(entry)
        with open(filename, 'w') as f:
            json.dump(log, f, indent=2)
        print(f'Logged run to {filename}')

    #  load preprocessed output from download_preprocess_ecg.py
    data_dict = load_ecg_data_matrix('data_ecg.pickle')
    data_all = data_dict['data_all']
    annotations_all = data_dict['annotations_all']
    onsets_all = data_dict['onsets_all']
    pt_codes_all = data_dict['pt_codes_all']

    #  artifact rejection
    data_all, annotations_all, onsets_all, pt_codes_all = remove_ecg_artifacts(
        data_all, annotations_all, onsets_all, pt_codes_all
    )

    #  binary labels
    ix, labels = make_binary_labels(annotations_all)
    data = data_all[ix, :]

    print(f'\nClass balance -> Normal: {(labels == 0).sum()}, '
          f'Abnormal: {(labels == 1).sum()}')

    #  split by patient
    pt_codes = pt_codes_all[ix]
    X_train, X_test, y_train, y_test = split_data_by_patient(data, labels, pt_codes)

    #  train KNN
    clf = train_knn(X_train, y_train)
    print(f'\nBest params: k={clf.best_params_["n_neighbors"]}, '
          f'weights={clf.best_params_["weights"]}')

    # evaluate (capture y_pred)
    y_pred, f1 = evaluate(clf, X_test, y_test, label='Held-out test set (binary KNN)')

    # save model
    dump(clf, 'Model_kNN_binary.joblib')
    print('\nSaved model to Model_kNN_binary.joblib')

    #  log results
    log_results(y_test, y_pred, clf.best_params_['n_neighbors'])